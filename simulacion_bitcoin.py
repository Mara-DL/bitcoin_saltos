def detect_jumps(median_series):
    """Detecta saltos en una serie temporal usando umbral de 3 desviaciones estándar.
    NOTA (limitación conocida, no corregida aquí): sobre ventanas cortas (p. ej.
    los 30 días del pronóstico) este umbral, al recalcularse sobre la propia
    submuestra, pierde poder discriminante y tiende a sobre-detectar."""
    log_returns = np.log(median_series[1:] / median_series[:-1])
    threshold_sim = 3 * np.std(log_returns)
    jump_flags = np.abs(log_returns) > threshold_sim
    jump_indices = np.where(jump_flags)[0] + 1
    jump_times = np.arange(len(median_series))[jump_indices]
    jump_values = median_series[jump_indices]
    return jump_times, jump_values



def download_and_load_binance():
    csv_path = "btc_daily_close.csv"
    if os.path.exists(csv_path):
        print("✅ Cargando datos históricos de Bitcoin desde CSV local...")
        df = pd.read_csv(csv_path, parse_dates=['fecha'])
        return df

    print("⚠️ CSV no encontrado. Iniciando descarga de datos minutales de Binance (2023-2025)...")
    def months(start, end):
        y, m = map(int, start.split('-'))
        y2, m2 = map(int, end.split('-'))
        while (y < y2) or (y == y2 and m <= m2):
            yield f"{y:04d}-{m:02d}"
            m += 1
            if m == 13:
                m = 1
                y += 1

    base = "https://data.binance.vision/data/spot/monthly/klines/BTCUSDT/1m/"
    zips = []
    for ym in months("2023-01", "2025-01"):
        fname = f"BTCUSDT-1m-{ym}.zip"
        url = base + fname
        r = requests.get(url, stream=True)
        if r.status_code == 200:
            with open(fname, 'wb') as f:
                for chunk in r.iter_content(1024 * 1024):
                    f.write(chunk)
            zips.append(fname)
        else:
            print(f"No encontrado: {fname}")

    columna3_total = []
    for z in zips:
        with zipfile.ZipFile(z, 'r') as zf:
            for nombre in zf.namelist():
                if nombre.endswith(".csv"):
                    df_zip = pd.read_csv(zf.open(nombre), header=None)
                    columna3_total.extend(df_zip.iloc[:, 2].values)  # Columna 3: Close

    df_min = pd.DataFrame(columna3_total, columns=["valor"])
    fechas = pd.date_range(start="2023-01-01", periods=len(df_min), freq="min")
    df_min["fecha"] = fechas

    df = df_min.set_index("fecha").resample("1D").last().dropna().reset_index()
    df.to_csv(csv_path, index=False)
    print("✅ Datos descargados, resampleados a diario y guardados en 'btc_daily_close.csv'")
    return df


df = download_and_load_binance()
df['valor'] = pd.to_numeric(df['valor'], errors='coerce')

X_mil_hist = np.zeros((N_sim, N_hist + 1))
X_mil_fc = np.zeros((N_sim, forecast_days + 1))
X_mil_hist[:, 0] = X0

# --- FIX 1: doble compensación del drift -----------------------------------
# Antes: drift_mil = mu_cont_hat * x * dt   (mu_cont_hat YA tenía restada la
#        contribución esperada de los saltos: lambda_hat*jump_mean)
#        y ADEMÁS se restaba otra vez vía 'comp = -(lambda_hat*jump_mean)*dt'.
#        comp y E[jump_pct] se cancelan exactamente, por lo que el drift
#        efectivo terminaba siendo mu_cont_hat en vez de mu_total_hat: la
#        contribución esperada de los saltos se restaba DOS veces.
# Ahora: el drift base usa mu_total_hat (el drift total observado). El
#        término 'comp' compensa el proceso de saltos para que
#        (jump_pct + comp) tenga media cero, tal como exige la Ec. (2) del
#        marco teórico (a(t,Y) - ∫R·ν(dz)) — sin restar el aporte de saltos
#        una segunda vez.
DRIFT_ANUALIZADO = mu_total_hat
# -----------------------------------------------------------------------------

for sim in range(N_sim):
    for i in range(N_hist):
        x_mil = X_mil_hist[sim, i]
        dW = np.sqrt(dt) * np.random.randn()
        n_jumps = np.random.poisson(lambda_hat * dt)
        jump_pct = np.sum(np.random.normal(jump_mean, jump_std, n_jumps)) if n_jumps > 0 else 0.0
        comp = -(lambda_hat * jump_mean) * dt

        drift_mil = DRIFT_ANUALIZADO * x_mil * dt   # FIX: antes mu_cont_hat
        diff_mil = sigma_daily * x_mil * dW
        corr_mil = 0.5 * (sigma_daily ** 2) * x_mil * (dW ** 2 - dt)

        X_mil_hist[sim, i + 1] = max(10.0, x_mil + drift_mil + diff_mil + corr_mil + (x_mil * comp) + (x_mil * jump_pct))

# Bucle Pronóstico
U0_mil = np.median(X_mil_hist[:, -1])
X_mil_fc[:, 0] = U0_mil

for sim in range(N_sim):
    for i in range(forecast_days):
        u_mil = X_mil_fc[sim, i]
        dW = np.sqrt(dt) * np.random.randn()
        n_jumps = np.random.poisson(lambda_hat * dt)
        jump_pct = np.sum(np.random.normal(jump_mean, jump_std, n_jumps)) if n_jumps > 0 else 0.0
        comp = -(lambda_hat * jump_mean) * dt

        X_mil_fc[sim, i + 1] = max(
            10.0,
            u_mil
            + DRIFT_ANUALIZADO * u_mil * dt          # FIX: antes mu_cont_hat
            + sigma_daily * u_mil * dW
            + 0.5 * (sigma_daily ** 2) * u_mil * (dW ** 2 - dt)
            + u_mil * comp
            + u_mil * jump_pct,
        )


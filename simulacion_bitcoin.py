# FASE 1: CALIBRACIÓN NO PARAMÉTRICA
# ==========================================
print("\n--- Calibrando parámetros (Variación Bipotencia + Umbral 4σ) ---")
df['log_retorno'] = np.log(df['valor'] / df['valor'].shift(1))
df = df.dropna().reset_index(drop=True)

dt = 1 / 365
T = len(df) * dt


def bipower_variation(retornos):
    """Devuelve la varianza continua PROMEDIO POR DÍA (normalizada por (n-1)).
    Se necesita en esta escala porque se usa como sigma_daily constante en la
    simulación diaria; NO debe compararse directamente contra una suma sin
    normalizar (ver FIX 2 más abajo)."""
    n = len(retornos)
    r = retornos.values
    bv = np.sum(np.abs(r[1:]) * np.abs(r[:-1]))  # vectorizado (antes: bucle for en Python)
    return (np.pi / 2) * bv / (n - 1)


sigma2_hat = bipower_variation(df['log_retorno'])

# --- FIX 2: comparar QV y BV en la MISMA escala (promedio por día) --------
# Antes: qv_total (suma total, ~n veces más grande) se restaba directamente
# de sigma2_hat (promedio por día), haciendo que jump_variation ≈ qv_total
# casi siempre (mezcla de escalas, resultado sin sentido).
n_obs = len(df)
qv_total = np.sum(df['log_retorno'] ** 2)
qv_avg = qv_total / (n_obs - 1)                      # ahora en la misma escala que sigma2_hat
jump_variation_avg = max(0.0, qv_avg - sigma2_hat)   # variación de saltos, promedio por día
jump_share_pct = 100 * jump_variation_avg / qv_avg if qv_avg > 0 else 0.0
# ---------------------------------------------------------------------------

sigma_daily = np.sqrt(sigma2_hat)
threshold = 4 * sigma_daily

df['es_salto'] = np.abs(df['log_retorno']) > threshold
num_saltos = int(df['es_salto'].sum())
lambda_hat = num_saltos / T

saltos = df[df['es_salto']]['log_retorno']
jump_mean = saltos.mean() if len(saltos) > 0 else 0.0
jump_std = saltos.std() if len(saltos) > 0 else 0.0

mu_total_hat = df['log_retorno'].mean() / dt
mu_cont_hat = mu_total_hat - (lambda_hat * jump_mean)

print(f"Volatilidad continua diaria (sigma):       {sigma_daily:.6f}")
print(f"Intensidad de saltos (lambda):              {lambda_hat:.2f} saltos/año")
print(f"Media de saltos (jump_mean):                {jump_mean:.6f}")
print(f"Drift TOTAL observado (mu_total, anualiz.):  {mu_total_hat:.4f}")
print(f"Drift continuo puro (mu_c, anualiz.):        {mu_cont_hat:.4f}  (solo diagnóstico, NO se usa como driver de la simulación)")
print(f"Variación de saltos / Variación cuadrática:  {jump_share_pct:.1f}%  (ambas en la misma escala, promedio diario)")


def bipower_variation(retornos):
    """Devuelve la varianza continua PROMEDIO POR DÍA (normalizada por (n-1)).
    Se necesita en esta escala porque se usa como sigma_daily constante en la
    simulación diaria; NO debe compararse directamente contra una suma sin
    normalizar (ver FIX 2 más abajo)."""
    n = len(retornos)
    r = retornos.values
    bv = np.sum(np.abs(r[1:]) * np.abs(r[:-1]))  # vectorizado (antes: bucle for en Python)
    return (np.pi / 2) * bv / (n - 1)


sigma2_hat = bipower_variation(df['log_retorno'])

# --- FIX 2: comparar QV y BV en la MISMA escala (promedio por día) --------
# Antes: qv_total (suma total, ~n veces más grande) se restaba directamente
# de sigma2_hat (promedio por día), haciendo que jump_variation ≈ qv_total
# casi siempre (mezcla de escalas, resultado sin sentido).

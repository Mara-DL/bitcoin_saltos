def paso_bonito(span, n=5):
    """Paso 1-2-5 x 10^k para la cuadrícula del zoom."""
    crudo = span / n
    base = 10 ** math.floor(math.log10(crudo))
    for f in (1, 2, 5, 10):
        if crudo <= f * base:
            return f * base
    return 10 * base



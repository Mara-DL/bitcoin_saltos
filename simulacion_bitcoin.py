        n_jumps = np.random.poisson(lambda_hat * dt)
        jump_pct = np.sum(np.random.normal(jump_mean, jump_std, n_jumps)) if n_jumps > 0 else 0.0
        comp = -(lambda_hat * jump_mean) * dt

